/// How long a block took in the guided mode (E7.19, decision D20). Mirrors the Tiempos sheet of the reference app.
library;

import 'base.dart';
import 'json.dart';
import 'plan.dart';

/// One run of one block of a session. Doing the same block twice leaves two of these, each with its own
/// client-generated [id]. The duration is derived from [start] and [end], never stored.
class BlockTime implements DelClub {
  const BlockTime({
    required this.id,
    required this.clubId,
    required this.sessionId,
    required this.blockIndex,
    required this.blockName,
    this.athleteMode,
    this.athleteIds = const [],
    required this.start,
    required this.end,
    this.interrupted = false,
    required this.auditoria,
  });

  /// Generated by the client, so repeating the write leaves one document.
  final String id;
  @override
  final String clubId;
  final String sessionId;

  /// Position of the block in the day (0-based).
  final int blockIndex;

  /// The block's name when it was done; renaming it later does not change history.
  final String blockName;

  /// How the athletes shared the block, or null when the block has no sets.
  final AthleteMode? athleteMode;

  /// The athletes who did it.
  final List<String> athleteIds;

  /// UTC instants.
  final DateTime start;
  final DateTime end;

  /// Whether the block was cut short.
  final bool interrupted;
  final Auditoria auditoria;

  /// Whole seconds between [start] and [end].
  int get seconds => end.difference(start).inSeconds;

  factory BlockTime.fromJson(Json j) => BlockTime(
    id: '${j['id']}',
    clubId: '${j['clubId']}',
    sessionId: '${j['sesionId']}',
    blockIndex: enteroOpcional(j['bloque'])!,
    blockName: '${j['bloqueNombre'] ?? ''}',
    athleteMode: j['modoAtletas'] == null
        ? null
        : AthleteMode.deCable(j['modoAtletas']),
    athleteIds: [for (final a in (j['atletaIds'] as List? ?? const [])) '$a'],
    start: DateTime.parse('${j['inicio']}').toUtc(),
    end: DateTime.parse('${j['fin']}').toUtc(),
    interrupted: j['interrumpido'] == true,
    auditoria: Auditoria.fromJson(
      (j['auditoria'] as Map).cast<String, dynamic>(),
    ),
  );

  Json toJson() => {
    'id': id,
    'clubId': clubId,
    'sesionId': sessionId,
    'bloque': blockIndex,
    'bloqueNombre': blockName,
    ...sinNulos({'modoAtletas': athleteMode?.cable}),
    'atletaIds': athleteIds,
    'inicio': start.toUtc().toIso8601String(),
    'fin': end.toUtc().toIso8601String(),
    'interrumpido': interrupted,
    'auditoria': auditoria.toJson(),
  };
}
